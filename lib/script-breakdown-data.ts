export type SeedBreakdown = {
  id: string;
  episode: string;
  sceneNo: number;
  sceneTitle: string;
  scriptText: string;
  sceneSummary: string;
  location: string;
  items: SeedBreakdownItem[];
};

const sourceVersion = '第一集《六十秒》V3（2026-09-05）';

function breakdown(
  sceneNo: number,
  sceneTitle: string,
  location: string,
  sceneSummary: string,
  scriptText: string,
  rows: Array<[SeedBreakdownItem['category'], string, string, string]>,
): SeedBreakdown {
  const id = `ep1-v3-s${sceneNo}`;
  return {
    id,
    episode: '第1集',
    sceneNo,
    sceneTitle,
    location,
    sceneSummary,
    scriptText: `${sourceVersion}\n${scriptText}`,
    items: rows.map(([category, name, detail, visualBrief], index) => ({
      id: `${id}-i${String(index + 1).padStart(2, '0')}`,
      analysisId: id,
      category,
      name,
      detail,
      visualBrief,
      sortOrder: index + 1,
    })),
  };
}

